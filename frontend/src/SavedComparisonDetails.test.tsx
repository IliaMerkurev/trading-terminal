import {it,expect,vi} from 'vitest';
import {render,screen,fireEvent,waitFor} from '@testing-library/react';
import SavedComparisonDetails from './SavedComparisonDetails';
import {api} from './api';
vi.mock('./api',()=>({api:vi.fn()}));
it('keeps unsaved text through polling and failure, then saves the confirmed revision',async()=>{
 const initial={name:'Original',notes:'',revision:0},onSaved=vi.fn();
 vi.mocked(api).mockRejectedValueOnce(Error('Synthetic disk failure')).mockResolvedValueOnce({name:'Draft',notes:'Research',revision:1});
 const {rerender}=render(<SavedComparisonDetails batchId="a" initial={initial} onSaved={onSaved}/>);
 fireEvent.click(screen.getByRole('button',{name:'Edit details'}));
 fireEvent.change(screen.getByLabelText('Comparison name'),{target:{value:'Draft'}});
 fireEvent.change(screen.getByLabelText('Research notes'),{target:{value:'Research'}});
 rerender(<SavedComparisonDetails batchId="a" initial={{...initial,name:'Polling value'}} onSaved={onSaved}/>);
 expect((screen.getByLabelText('Comparison name') as HTMLInputElement).value).toBe('Draft');
 fireEvent.click(screen.getByText('Save details'));
 expect((await screen.findByRole('alert')).textContent).toContain('Your text is retained');
 expect(onSaved).not.toHaveBeenCalled();
 expect((screen.getByRole('button',{name:'Hide details'}) as HTMLButtonElement).disabled).toBe(true);
 expect((screen.getByLabelText('Comparison name') as HTMLInputElement).value).toBe('Draft');
 fireEvent.click(screen.getByText('Save details'));
 await screen.findByText('Comparison details saved.');
 expect(screen.queryByLabelText('Comparison name')).toBeNull();
 expect(screen.getByRole('button',{name:'Edit details'}).getAttribute('aria-expanded')).toBe('false');
 fireEvent.click(screen.getByRole('button',{name:'Edit details'}));
 expect((screen.getByLabelText('Comparison name') as HTMLInputElement).value).toBe('Draft');
 expect(api).toHaveBeenLastCalledWith('library_batch_save_metadata',{batch_id:'a',name:'Draft',notes:'Research',expected_revision:0});
 expect(onSaved).toHaveBeenCalledWith({name:'Draft',notes:'Research',revision:1});
});
it('reloads after a revision conflict and allows clearing metadata',async()=>{
 vi.mocked(api).mockResolvedValueOnce({name:'Other editor',notes:'Changed',revision:3}).mockResolvedValueOnce({name:'',notes:'',revision:4});
 render(<SavedComparisonDetails batchId="b" initial={{name:'Old',notes:'',revision:1}} onSaved={vi.fn()}/>);
 fireEvent.click(screen.getByRole('button',{name:'Edit details'}));
 fireEvent.change(screen.getByLabelText('Comparison name'),{target:{value:'Draft'}});
 fireEvent.click(screen.getByText('Discard edits and reload saved details'));
 await waitFor(()=>expect((screen.getByLabelText('Comparison name') as HTMLInputElement).value).toBe('Other editor'));
 fireEvent.change(screen.getByLabelText('Comparison name'),{target:{value:''}});fireEvent.change(screen.getByLabelText('Research notes'),{target:{value:''}});
 fireEvent.click(screen.getByText('Save details'));await screen.findByText('Comparison details saved.');
 expect(api).toHaveBeenLastCalledWith('library_batch_save_metadata',{batch_id:'b',name:'',notes:'',expected_revision:3});
});
it('keeps saved notes behind a focusable disclosure without editing or saving',()=>{
 vi.mocked(api).mockClear();
 render(<SavedComparisonDetails batchId="notes" initial={{name:'Named comparison',notes:'Complete saved note',revision:1}} onSaved={vi.fn()}/>);
 expect(screen.getByRole('heading',{name:'Named comparison'})).toBeTruthy();
 const summary=screen.getByText('Saved notes',{selector:'summary'});
 expect(summary.closest('details')?.open).toBe(false);summary.focus();expect(document.activeElement).toBe(summary);
 fireEvent.click(summary);expect(summary.closest('details')?.open).toBe(true);expect(screen.getByText('Complete saved note')).toBeTruthy();
 fireEvent.click(summary);expect(summary.closest('details')?.open).toBe(false);
 expect(screen.queryByLabelText('Research notes')).toBeNull();expect(api).not.toHaveBeenCalled();
 fireEvent.click(screen.getByRole('button',{name:'Edit details'}));
 expect((screen.getByLabelText('Research notes') as HTMLTextAreaElement).value).toBe('Complete saved note');
});
